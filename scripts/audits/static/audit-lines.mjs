// Static audit for DG-01, "Never a Straight Line" (docs/design/01-drawing-grammar.md).
//
// Nothing in the root/neural/light system may be drawn as a perfectly straight
// segment: no <line> elements, no L-only path data, no zero-bow filaments. The
// rule was previously enforced by remembering it. This makes it fail the build.
//
// Scope: src/components (figures, diagrams, the Orrery, the organic primitives).
// The background data-grid is the one sanctioned exception and is allow-listed.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const SCAN_DIR = join(ROOT, 'src', 'components');

// Files permitted to draw technical backdrop geometry rather than tissue.
const ALLOWLIST = new Set([
  'src/components/figures/FigurePrimitives.tsx' // owns <pattern> grid + DataTicks
]);

const violations = [];

function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else if (/\.(tsx|ts)$/.test(entry)) inspect(full);
  }
}

function inspect(file) {
  const rel = relative(ROOT, file).replace(/\\/g, '/');
  if (ALLOWLIST.has(rel)) return;

  const src = readFileSync(file, 'utf8');
  const lines = src.split(/\r?\n/);

  lines.forEach((line, i) => {
    const at = `${rel}:${i + 1}`;

    if (/<line\b/.test(line)) {
      violations.push({ at, rule: 'no <line> elements', text: line.trim() });
    }

    // Path data that only ever moves and draws straight segments.
    const dMatch = line.match(/\bd=(?:"|\{`|`)([^"`]+)(?:"|`)/);
    if (dMatch) {
      const d = dMatch[1];
      const hasCurve = /[CcSsQqTtAa]/.test(d);
      const hasLine = /[LlHhVv]/.test(d);
      // Template-interpolated path data is generated by smoothPolyline/arcSegment
      // and cannot be judged statically; only literal path data is checked.
      const isLiteral = !d.includes('${');
      if (isLiteral && hasLine && !hasCurve) {
        violations.push({ at, rule: 'L-only path (no curvature)', text: d });
      }
    }
  });
}

walk(SCAN_DIR);

if (violations.length) {
  console.error(`\naudit-lines: ${violations.length} straight-line violation(s)\n`);
  for (const v of violations) console.error(`  ${v.at}\n    ${v.rule}\n    ${v.text}\n`);
  console.error('See DG-01, "Never a Straight Line" — docs/design/01-drawing-grammar.md\n');
  process.exit(1);
}

console.log('audit-lines: clean — no straight segments in the tissue.');
